export function detectDisplayCurrency(
  country?: string,
  timeZone?: string,
  locale?: string,
): string | null {
  const fromCountry = currencyForCountry(country);
  if (fromCountry) return fromCountry;
  const fromTimeZone = currencyForCountry(TIME_ZONE_COUNTRIES[timeZone ?? ""]);
  if (fromTimeZone) return fromTimeZone;
  try {
    // Do not maximize a language into an assumed country (e.g. English -> US).
    return currencyForCountry(locale ? new Intl.Locale(locale).region : undefined);
  } catch {
    return null;
  }
}

export function formatEstimate(amount: number, currency: string, locale?: string): string {
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency,
    currencyDisplay: "code",
    // A naira share can cost much less than one cent in another currency.
    ...(amount !== 0 && Math.abs(amount) < 0.01 ? { maximumSignificantDigits: 2 } : {}),
  }).format(amount);
}
